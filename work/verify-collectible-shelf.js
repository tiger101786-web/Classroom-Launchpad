const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async ({ page, browser, baseUrl, request, studentCookie, teacherCookie, dataDir }) => {
  const post = (body, cookie = studentCookie) => request('/api/home-shelf', { method:'POST', body, cookie });
  const choice = { enabled:true, slots:['trophy','crystal','planet'], theme:'crimson' };
  assert.equal((await post({...choice,theme:'../invalid'})).status,400);
  assert.equal((await post(choice, '')).status, 401);
  for (const value of [{ ...choice, slots:['alien'] }, { ...choice, slots:['invalid','none','none'] }, { ...choice, enabled:'yes' }]) assert.equal((await post(value)).status,400);
  assert.equal((await post({ enabled:false, slots:['robot','none','books'] },teacherCookie)).status,200);
  await page.locator('.home-collectible-shelf').waitFor();
  await page.locator('.header-account-summary:visible').click();
  const menuShelf = page.locator('.header-account-links [data-action="collectibleShelf"]');
  assert.equal(await menuShelf.evaluate(button => button.previousElementSibling.textContent.trim()), '◉My Profile');
  assert.equal(await menuShelf.locator('span[aria-hidden="true"]').textContent(), '⚙');
  assert.equal(await menuShelf.locator('span').evaluate(icon => getComputedStyle(icon).color), await page.locator('.header-account-links button').first().locator('span').evaluate(icon => getComputedStyle(icon).color));
  await page.screenshot({path:path.join(dataDir,'shelf-account-menu.png')});
  await page.locator('.header-account-summary:visible').click();
  async function open() {
    await page.locator('.home-collectible-shelf').hover();
    await page.locator('.shelf-customize').click();
    await page.locator('#shelfSettingsMenu [data-action="collectibleShelf"]').click();
  }
  await open();
  assert.equal(await page.locator('[data-shelf-item="medal"]').count(),0);
  for (const id of ['electric-guitar','drum-kit','violin','grand-piano']) assert.equal(await page.locator(`[data-shelf-item="${id}"]`).count(),0);
  await page.locator('#shelfCategory').selectOption({label:'Shelf Decorations'});
  assert.equal(await page.locator('[data-shelf-item]').count(),5);
  await page.locator('[data-shelf-item="ceramic-fox"]').click();
  assert.equal(await page.locator('#shelfPreview [aria-label="Ceramic Fox"]').count(),1);
  await page.locator('#shelfCategory').selectOption({label:'Anime'});
  assert.equal(await page.locator('[data-shelf-item]').count(),11);
  await page.locator('[data-shelf-item="tanjiro"]').click();
  assert.equal(await page.locator('#shelfPreview [aria-label="Tanjiro Bust"]').count(),1);
  await page.locator('#shelfCategory').selectOption('');
  assert.equal(await page.locator('[data-shelf-item]').count(),96);
  assert.equal(await page.locator('[data-shelf-item="book-nook"]').count(),0);
  assert.equal(await page.locator('[data-shelf-slot]').count(),3);
  await page.locator('[data-shelf-item="trophy"]').click();
  await page.locator('[data-shelf-slot="1"]').click();
  await page.locator('#shelfSearch').fill('crystal');
  assert.equal(await page.locator('[data-shelf-item]').count(),3);
  await page.locator('[data-shelf-item="crystal"]').click();
  await page.locator('#shelfSearch').fill('nothing-matches');
  assert.equal(await page.locator('[data-shelf-item]').count(),1);
  await page.locator('#shelfSearch').fill('');
  await page.locator('#shelfCategory').selectOption({label:'Space'});
  assert.equal(await page.locator('[data-shelf-item]').count(),7);
  await page.locator('[data-shelf-slot="2"]').click();
  await page.locator('[data-shelf-item="planet"]').click();
  await page.locator('#shelfCategory').selectOption('');
  await page.screenshot({path:path.join(dataDir,'shelf-chooser-desktop.png')});
  await page.locator('#shelfChoices').screenshot({path:path.join(dataDir,'shelf-all-objects.png')});
  await page.locator('#saveShelf').click();
  await page.locator('.shelf-dialog').waitFor({state:'detached'});
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.shelf-customize')).opacity === '0', { }, {timeout:1800});
  await page.locator('.home-collectible-shelf').hover();
  await page.locator('.shelf-customize').click();
  await page.mouse.click(1,1);
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.shelf-customize')).opacity === '0', { }, {timeout:1800});
  await page.reload({waitUntil:'networkidle'});
  assert.deepEqual((await request('/api/auth/session',{cookie:studentCookie})).payload.session.homeShelf,choice);
  assert.equal((await request('/api/auth/session',{cookie:teacherCookie})).payload.session.homeShelf.enabled,false);
  for (const width of [1280,1024,390]) {
    await page.setViewportSize({width,height:900});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
    const shelf = await page.locator('.home-collectible-shelf').boundingBox();
    const scene = await page.locator('.launch-scene-stage').boundingBox();
    assert(shelf.x+shelf.width <= scene.x || shelf.y+shelf.height <= scene.y || shelf.x >= scene.x+scene.width || shelf.y >= scene.y+scene.height, `No shelf/scene overlap at ${width}`);
    await page.screenshot({path:path.join(dataDir,`shelf-home-${width}.png`)});
    await open();
    assert.equal(await page.locator('.shelf-dialog').evaluate(el => el.scrollWidth > el.clientWidth),false);
    if(width === 390) await page.screenshot({path:path.join(dataDir,'shelf-chooser-mobile.png')});
    await page.keyboard.press('Escape');
  }
  await page.setViewportSize({width:1280,height:900});
  await open();
  await page.locator('[data-shelf-item="none"]').click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await page.locator('.home-collectible-shelf [aria-label="Gold Trophy"]').count(),1);
  await open();
  await page.route('**/api/home-shelf',route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({error:'Test save failed'})}));
  await page.locator('#saveShelf').click();
  await page.waitForFunction(()=>document.querySelector('#shelfSaveStatus')?.textContent === 'Test save failed');
  assert.equal(await page.locator('#saveShelf').isEnabled(),true);
  await page.unroute('**/api/home-shelf');
  await page.locator('#shelfEnabled').uncheck();
  await page.locator('#saveShelf').click();
  await page.locator('.shelf-dialog').waitFor({state:'detached'});
  assert.equal(await page.locator('.home-collectible-shelf').count(),0);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.home-collectible-shelf').count(),0);
  await page.locator('.header-account-summary:visible').click();
  await page.locator('[data-action="collectibleShelf"]:visible').click();
  await page.locator('#shelfEnabled').check();
  await page.locator('[data-shelf-item="none"]').click();
  await page.locator('#saveShelf').click();
  await page.locator('.shelf-dialog').waitFor({state:'detached'});
  assert.equal(await page.locator('.home-collectible-shelf .shelf-empty').count(),1);
  const migrated = await post({enabled:true,slots:['medal','crystal','planet']});
  assert.deepEqual(migrated.payload.session.homeShelf.slots,['tanjiro','crystal','planet']);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.home-collectible-shelf [aria-label="Tanjiro Bust"]').count(),1);
  await page.screenshot({path:path.join(dataDir,'shelf-tanjiro-desktop.png')});
  await post({enabled:true,slots:['none','crystal','planet']});
  await page.reload({waitUntil:'networkidle'});
  await page.locator('.home-collectible-shelf').hover();
  await page.locator('.shelf-customize').click();
  await page.getByRole('button',{name:'Hide shelf',exact:true}).click();
  await page.locator('.home-collectible-shelf').waitFor({state:'detached'});
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.home-collectible-shelf').count(),0);
  assert.deepEqual((await request('/api/auth/session',{cookie:studentCookie})).payload.session.homeShelf, {enabled:false,slots:['none','crystal','planet'],theme:'crimson'});
  await page.getByRole('button',{name:'Show shelf',exact:true}).click();
  await page.locator('.home-collectible-shelf').waitFor();
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.home-collectible-shelf .shelf-empty').count(),1);
  await open();
  await page.locator('#shelfCategory').selectOption({label:'Anime'});
  await page.locator('[data-shelf-item="all-might"]').click();
  await page.locator('[data-shelf-slot="1"]').click();
  await page.locator('[data-shelf-item="naruto"]').click();
  await page.locator('[data-shelf-slot="2"]').click();
  await page.locator('[data-shelf-item="tanjiro"]').click();
  await page.locator('#saveShelf').click();
  await page.locator('.shelf-dialog').waitFor({state:'detached'});
  await page.reload({waitUntil:'networkidle'});
  assert.deepEqual((await request('/api/auth/session',{cookie:studentCookie})).payload.session.homeShelf.slots,['all-might','naruto','tanjiro']);
  await page.screenshot({path:path.join(dataDir,'shelf-anime-statues.png')});
  const newItems = ['goku','pikachu','eevee','crystal-dragon','moon-astronaut','race-car','ship-bottle','knight-helmet','streetcar','saxophone','pinball','snow-globe','owl-books'];
  newItems.push('ceramic-fox','succulent','trumpet','hourglass','mantel-clock','microscope','telescope','dna','atom','earth-globe','hot-air-balloon','compass','lighthouse','biplane','steam-train','treasure-chest','phoenix','potion','beignets','cupcake');
  for (const [oldId,newId] of Object.entries({'electric-guitar':'ceramic-fox','drum-kit':'succulent',violin:'hourglass','grand-piano':'mantel-clock'})) {
    const migrated = await post({enabled:false,slots:[oldId,'books','none']});
    assert.deepEqual(migrated.payload.session.homeShelf,{enabled:false,slots:[newId,'books','none'],theme:'crimson'});
  }
  newItems.push('nezuko','red-panda','penguin','axolotl','hedgehog','lucky-cat','terrarium','mushroom-house','lantern','music-box','teacup','rubber-duck','origami-crane','ammonite','geode','message-bottle','jewelry-box','snowman','pumpkin-lantern','sandcastle','luffy','daisy-vase');
  for (const id of newItems) {
    const result = await post({enabled:true,slots:[id,'none','none']});
    assert.equal(result.status,200);
    assert.equal(result.payload.session.homeShelf.slots[0],id);
  }
  for (const id of ['sailor-moon','rumi']) {
    await open();
    await page.locator('#shelfSearch').fill(id === 'rumi' ? 'Rumi' : 'Sailor Moon');
    await page.locator(`[data-shelf-item="${id}"]`).click();
    await page.locator('#saveShelf').click();
    await page.locator('.shelf-dialog').waitFor({state:'detached'});
    await page.reload({waitUntil:'networkidle'});
    assert((await request('/api/auth/session',{cookie:studentCookie})).payload.session.homeShelf.slots.includes(id));
    assert.equal(await page.locator(`.home-collectible-shelf image[href="assets/shelf-${id}.png"]`).count(),1);
  }
  await post({enabled:true,slots:['goku','pikachu','eevee']});
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.home-collectible-shelf [aria-label="Pikachu"]').count(),1);
  await page.screenshot({path:path.join(dataDir,'shelf-goku-pokemon.png')});
  await open();
  await page.locator('#shelfSearch').fill('nezuko');
  assert.equal(await page.locator('[data-shelf-item]').count(),2);
  await page.locator('[data-shelf-slot="0"]').click();
  await page.locator('[data-shelf-item="nezuko"]').click();
  await page.locator('[data-shelf-slot="1"]').click();
  await page.locator('#shelfSearch').fill('luffy');
  await page.locator('[data-shelf-item="luffy"]').click();
  await page.locator('[data-shelf-slot="2"]').click();
  await page.locator('#shelfSearch').fill('daisy');
  await page.locator('[data-shelf-item="daisy-vase"]').click();
  await page.locator('#saveShelf').click();
  await page.locator('.shelf-dialog').waitFor({state:'detached'});
  await page.reload({waitUntil:'networkidle'});
  assert.deepEqual((await request('/api/auth/session',{cookie:studentCookie})).payload.session.homeShelf.slots,['nezuko','luffy','daisy-vase']);
  for(const label of ['Nezuko Statue','Luffy Bust','Daisy Vase']) assert.equal(await page.locator(`.home-collectible-shelf [aria-label="${label}"]`).count(),1);
  await page.screenshot({path:path.join(dataDir,'shelf-nezuko-luffy.png')});
  const shelfThemes = require('../collectible-shelf').themes;
  for (const theme of shelfThemes) {
    await open();
    assert.equal(await page.locator('[data-shelf-theme-choice]').count(),7);
    await page.locator(`[data-shelf-theme-choice="${theme.id}"]`).click();
    assert.equal(await page.locator('#shelfPreview .collectible-shelf').getAttribute('data-shelf-theme'),theme.id);
    assert.equal(await page.locator('#shelfPreview [aria-label="Nezuko Statue"]').count(),1);
    await page.locator('#saveShelf').click();
    await page.locator('.shelf-dialog').waitFor({state:'detached'});
    await page.reload({waitUntil:'networkidle'});
    const saved = (await request('/api/auth/session',{cookie:studentCookie})).payload.session.homeShelf;
    assert.equal(saved.theme,theme.id);
    assert.deepEqual(saved.slots,['nezuko','luffy','daisy-vase']);
    assert.equal(await page.locator('.home-collectible-shelf .collectible-shelf').getAttribute('data-shelf-theme'),theme.id);
  }
  assert.equal((await request('/api/auth/session',{cookie:teacherCookie})).payload.session.homeShelf.theme,'crimson');
  await open();
  await page.locator('[data-shelf-theme-choice="ice"]').click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await page.locator('.home-collectible-shelf .collectible-shelf').getAttribute('data-shelf-theme'),'royal');
  await open();
  await page.locator('[data-shelf-theme-choice="ocean"]').click();
  await page.route('**/api/home-shelf', route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({error:'Theme save failed'})}));
  await page.locator('#saveShelf').click();
  await page.getByText('Theme save failed',{exact:true}).waitFor();
  assert.equal(await page.locator('[data-shelf-theme-choice="ocean"]').isEnabled(),true);
  await page.unroute('**/api/home-shelf');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.locator('.home-collectible-shelf').hover();
  await page.locator('.shelf-customize').click();
  await page.getByRole('button',{name:'Hide shelf',exact:true}).click();
  await page.getByRole('button',{name:'Show shelf',exact:true}).click();
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.home-collectible-shelf .collectible-shelf').getAttribute('data-shelf-theme'),'royal');
  await page.setViewportSize({width:390,height:844});
  await open();
  await page.locator('.shelf-theme-grid .shelf-board').evaluateAll(boards => Promise.all(boards.map(board => {
    const image = new Image();
    image.src = getComputedStyle(board).backgroundImage.slice(5,-2);
    return image.decode();
  })));
  assert.equal(await page.locator('.shelf-dialog').evaluate(el=>el.scrollWidth>el.clientWidth),false);
  await page.screenshot({path:path.join(dataDir,'shelf-theme-chooser-mobile.png')});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:1280,height:900});
  const guest=await browser.newPage();
  await guest.goto(baseUrl,{waitUntil:'networkidle'});
  assert.equal(await guest.locator('.home-collectible-shelf, [data-action="collectibleShelf"]').count(),0);
  await guest.close();
  await page.reload({waitUntil:'networkidle'});
};
