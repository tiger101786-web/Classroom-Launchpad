const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async ({ page, browser, baseUrl, request, studentCookie, teacherCookie, dataDir }) => {
  const post = (body, cookie = studentCookie) => request('/api/home-shelf', { method:'POST', body, cookie });
  const choice = { enabled:true, slots:['trophy','crystal','planet'] };
  assert.equal((await post(choice, '')).status, 401);
  for (const value of [{ ...choice, slots:['alien'] }, { ...choice, slots:['invalid','none','none'] }, { ...choice, enabled:'yes' }]) assert.equal((await post(value)).status,400);
  assert.equal((await post({ enabled:false, slots:['robot','none','books'] },teacherCookie)).status,200);
  await page.locator('.home-collectible-shelf').waitFor();
  async function open() {
    await page.locator('.home-collectible-shelf').hover();
    await page.locator('.shelf-customize').click();
    await page.locator('#shelfSettingsMenu [data-action="collectibleShelf"]').click();
  }
  await open();
  assert.equal(await page.locator('[data-shelf-item="medal"]').count(),0);
  await page.locator('#shelfCategory').selectOption({label:'Anime'});
  assert.equal(await page.locator('[data-shelf-item]').count(),2);
  await page.locator('[data-shelf-item="tanjiro"]').click();
  assert.equal(await page.locator('#shelfPreview [aria-label="Tanjiro Bust"]').count(),1);
  await page.locator('#shelfCategory').selectOption('');
  assert.equal(await page.locator('[data-shelf-item]').count(),37);
  assert.equal(await page.locator('[data-shelf-slot]').count(),3);
  await page.locator('[data-shelf-item="trophy"]').click();
  await page.locator('[data-shelf-slot="1"]').click();
  await page.locator('#shelfSearch').fill('crystal');
  assert.equal(await page.locator('[data-shelf-item]').count(),2);
  await page.locator('[data-shelf-item="crystal"]').click();
  await page.locator('#shelfSearch').fill('nothing-matches');
  assert.equal(await page.locator('[data-shelf-item]').count(),1);
  await page.locator('#shelfSearch').fill('');
  await page.locator('#shelfCategory').selectOption({label:'Space'});
  assert.equal(await page.locator('[data-shelf-item]').count(),7);
  await page.locator('[data-shelf-slot="2"]').click();
  await page.locator('[data-shelf-item="planet"]').click();
  await page.locator('#shelfCategory').selectOption('');
  await page.screenshot({path:path.join(dataDir,'shelf-chooser-desktop.png')});
  await page.locator('#shelfChoices').screenshot({path:path.join(dataDir,'shelf-all-objects.png')});
  await page.locator('#saveShelf').click();
  await page.locator('.shelf-dialog').waitFor({state:'detached'});
  await page.reload({waitUntil:'networkidle'});
  assert.deepEqual((await request('/api/auth/session',{cookie:studentCookie})).payload.session.homeShelf,choice);
  assert.equal((await request('/api/auth/session',{cookie:teacherCookie})).payload.session.homeShelf.enabled,false);
  for (const width of [1280,1024,390]) {
    await page.setViewportSize({width,height:900});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
    const shelf = await page.locator('.home-collectible-shelf').boundingBox();
    const scene = await page.locator('.launch-scene-stage').boundingBox();
    assert(shelf.x+shelf.width <= scene.x || shelf.y+shelf.height <= scene.y || shelf.x >= scene.x+scene.width || shelf.y >= scene.y+scene.height, `No shelf/scene overlap at ${width}`);
    await page.screenshot({path:path.join(dataDir,`shelf-home-${width}.png`)});
    await open();
    assert.equal(await page.locator('.shelf-dialog').evaluate(el => el.scrollWidth > el.clientWidth),false);
    if(width === 390) await page.screenshot({path:path.join(dataDir,'shelf-chooser-mobile.png')});
    await page.keyboard.press('Escape');
  }
  await page.setViewportSize({width:1280,height:900});
  await open();
  await page.locator('[data-shelf-item="none"]').click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await page.locator('.home-collectible-shelf [aria-label="Gold Trophy"]').count(),1);
  await open();
  await page.route('**/api/home-shelf',route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({error:'Test save failed'})}));
  await page.locator('#saveShelf').click();
  await page.waitForFunction(()=>document.querySelector('#shelfSaveStatus')?.textContent === 'Test save failed');
  assert.equal(await page.locator('#saveShelf').isEnabled(),true);
  await page.unroute('**/api/home-shelf');
  await page.locator('#shelfEnabled').uncheck();
  await page.locator('#saveShelf').click();
  await page.locator('.shelf-dialog').waitFor({state:'detached'});
  assert.equal(await page.locator('.home-collectible-shelf').count(),0);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.home-collectible-shelf').count(),0);
  await page.locator('.header-account-summary:visible').click();
  await page.locator('[data-action="collectibleShelf"]:visible').click();
  await page.locator('#shelfEnabled').check();
  await page.locator('[data-shelf-item="none"]').click();
  await page.locator('#saveShelf').click();
  await page.locator('.shelf-dialog').waitFor({state:'detached'});
  assert.equal(await page.locator('.home-collectible-shelf .shelf-empty').count(),1);
  const migrated = await post({enabled:true,slots:['medal','crystal','planet']});
  assert.deepEqual(migrated.payload.session.homeShelf.slots,['tanjiro','crystal','planet']);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.home-collectible-shelf [aria-label="Tanjiro Bust"]').count(),1);
  await page.screenshot({path:path.join(dataDir,'shelf-tanjiro-desktop.png')});
  await post({enabled:true,slots:['none','crystal','planet']});
  await page.reload({waitUntil:'networkidle'});
  await page.locator('.home-collectible-shelf').hover();
  await page.locator('.shelf-customize').click();
  await page.getByRole('button',{name:'Hide shelf',exact:true}).click();
  await page.locator('.home-collectible-shelf').waitFor({state:'detached'});
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.home-collectible-shelf').count(),0);
  assert.deepEqual((await request('/api/auth/session',{cookie:studentCookie})).payload.session.homeShelf, {enabled:false,slots:['none','crystal','planet']});
  const guest=await browser.newPage();
  await guest.goto(baseUrl,{waitUntil:'networkidle'});
  assert.equal(await guest.locator('.home-collectible-shelf, [data-action="collectibleShelf"]').count(),0);
  await guest.close();
  await page.reload({waitUntil:'networkidle'});
};
